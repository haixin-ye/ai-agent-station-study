const orderedCases = [...cases].sort((left, right) => {
  const leftFamily = Math.min(...left.tags.map(tag => familyOrder.indexOf(tag)).filter(index => index >= 0));
  const rightFamily = Math.min(...right.tags.map(tag => familyOrder.indexOf(tag)).filter(index => index >= 0));
  return leftFamily - rightFamily || Number(left.externalId) - Number(right.externalId);
});

