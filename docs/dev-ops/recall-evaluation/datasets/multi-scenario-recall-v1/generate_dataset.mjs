function id(base, scenarioIndex, itemIndex) {
  return String(base + scenarioIndex * 10 + itemIndex);
}

function expected(externalId, type, grade = 3) {
  return { externalId, grade, matchMode: type === 'RAG_DOCUMENT' ? 'PARENT_DOCUMENT' : 'EXACT_SOURCE' };
}

scenarios.forEach((scenario, scenarioIndex) => {
  if (scenario.rag.length !== 10 || scenario.memory.length !== 10 || scenario.preference.length !== 10 || scenario.mixed.length !== 6) {
    throw new Error(`Invalid scenario shape: ${scenario.key}`);
  }
  scenario.rag.forEach(([title, content], itemIndex) => rag.push({
    externalId: id(10001, scenarioIndex, itemIndex), type: 'RAG_DOCUMENT', title,
    summary: content.slice(0, 72), content, tags: [scenario.key, scenario.name, 'RAG', `topic-${itemIndex + 1}`]
  }));
  scenario.memory.forEach(([summary, content], itemIndex) => longTermMemory.push({
    externalId: id(20001, scenarioIndex, itemIndex), type: 'LONG_TERM_MEMORY', title: summary,
    summary, content, score: 0.85, tags: [scenario.key, scenario.name, '长期记忆', `fact-${itemIndex + 1}`]
  }));
  scenario.preference.forEach(([summary, content], itemIndex) => userPreference.push({
    externalId: id(30001, scenarioIndex, itemIndex), type: 'USER_PREFERENCE', title: summary,
    summary, content, score: 0.9, tags: [scenario.key, scenario.name, '用户偏好', `preference-${itemIndex + 1}`]
  }));

  let caseIndex = 0;
  const addCase = (query, scope, labels, kind, extraTags = []) => {
    cases.push({
      externalId: String(40001 + scenarioIndex * 25 + caseIndex++), query, sourceScope: scope,
      expected: labels, tags: [scenario.key, scenario.name, kind, ...extraTags]
    });
  };

  for (let i = 0; i < 5; i++) {
    const [title] = scenario.rag[i];
    addCase(`不直接照搬标题，请概括资料中“${title}”真正需要注意的决策条件和限制。`, 'RAG',
      [expected(id(10001, scenarioIndex, i), 'RAG_DOCUMENT')], 'RAG改写问题');
  }
  for (let i = 0; i < 4; i++) {
    const [summary] = scenario.memory[i];
    addCase(`回顾已有记录，我在“${summary}”这件事上的具体情况是什么？不要使用通用常识代替个人记录。`, 'MEMORY',
      [expected(id(20001, scenarioIndex, i), 'LONG_TERM_MEMORY')], '长期记忆改写问题');
  }
  for (let i = 0; i < 4; i++) {
    const [summary] = scenario.preference[i];
    addCase(`做相关选择时，我对“${summary}”表现出的稳定偏好是什么？`, 'MEMORY',
      [expected(id(30001, scenarioIndex, i), 'USER_PREFERENCE')], '偏好改写问题');
  }
  for (let i = 0; i < 6; i++) {
    addCase(scenario.mixed[i], 'MIXED', [
      expected(id(10001, scenarioIndex, i), 'RAG_DOCUMENT', 2),
      expected(id(20001, scenarioIndex, i), 'LONG_TERM_MEMORY', 3),
      expected(id(30001, scenarioIndex, i), 'USER_PREFERENCE', 3)
    ], '跨来源组合问题', ['multi-label']);
  }
  for (let i = 5; i < 8; i++) {
    const [title] = scenario.rag[i];
    const distractor = scenario.rag[(i + 1) % 10][0];
    addCase(`我关心的是${title}中的约束，不是${distractor}。资料里应优先采用哪些信息？`, 'RAG',
      [expected(id(10001, scenarioIndex, i), 'RAG_DOCUMENT')], '同主题干扰问题', ['hard-negative']);
  }
  for (let i = 4; i < 7; i++) {
    const [summary] = scenario.memory[i];
    const distractor = scenario.preference[(i + 2) % 10][0];
    addCase(`不要把“${distractor}”当作事实。已有记录里与“${summary}”对应的真实情况是什么？`, 'MEMORY',
      [expected(id(20001, scenarioIndex, i), 'LONG_TERM_MEMORY')], '记忆偏好干扰问题', ['hard-negative']);
  }
  if (caseIndex !== 25) throw new Error(`Unexpected case count for ${scenario.key}: ${caseIndex}`);
});

